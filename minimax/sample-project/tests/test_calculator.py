"""Target tests for SPEC-001 section 2.1.

These tests are written before the feature exists and they are not modified
afterwards. Before the change they fail with a plain assertion error, which is
what makes them a valid "the behaviour was missing" baseline rather than a
broken environment.

Do not edit this file between the before and after runs. The MiniMax topic
checks that the test set stays identical across the change.
"""

import pytest

from tinycalc import Calculator


class TestMinValueFilter:
    """The filter introduced by SPEC-001 section 2.1."""

    def test_min_value_keeps_values_at_or_above_the_bound(self):
        assert Calculator([1, 5, 9]).apply(min_value=5) == [5, 9]

    def test_min_value_keeps_everything_when_the_bound_is_lowest(self):
        assert Calculator([1, 5, 9]).apply(min_value=1) == [1, 5, 9]

    def test_min_value_keeps_nothing_when_the_bound_is_highest(self):
        assert Calculator([1, 5, 9]).apply(min_value=10) == []

    def test_min_value_rejects_a_non_integer(self):
        with pytest.raises(ValueError):
            Calculator([1, 2]).apply(min_value="x")

    def test_min_value_rejects_a_negative_bound(self):
        with pytest.raises(ValueError):
            Calculator([1, 2]).apply(min_value=-1)


class TestExistingBehaviour:
    """Behaviour that already shipped and must keep working."""

    def test_max_value_keeps_values_at_or_below_the_bound(self):
        assert Calculator([1, 5, 9]).apply(max_value=5) == [1, 5]

    def test_no_filter_returns_a_copy_of_the_values(self):
        calculator = Calculator([3, 1, 2])
        result = calculator.apply()
        assert result == [3, 1, 2]
        assert result is not calculator.values

    def test_the_input_order_is_preserved(self):
        assert Calculator([9, 1, 5]).apply(max_value=10) == [9, 1, 5]

    def test_total_sums_the_filtered_values(self):
        assert Calculator([1, 2, 3]).total(max_value=2) == 3
